a = int(input("Введите A: "))  # Начало диапазона
b = int(input("Введите B: "))  # Конец диапазона

s = 0  # Разность сумм

for i in range(a, b + 1):  # Перебираем числа от A до B
    if i % 2 == 0:  # Если число чётное
        s += i  # Прибавляем к сумме
    else:  # Если число нечётное
        s -= i  # Вычитаем из суммы

print(s)  # Выводим разность сумм