n = int(input('Введите число: '))  # Вводим число n
count = 0  # Счётчик подходящих чисел

for i in range(1, n + 1):  # Перебираем числа от 1 до n
    if i % 2 != 0 and i % 3 != 0 and i % 5 != 0:  # Проверяем, что число не делится на 2, 3 и 5
        count += 1  # Увеличиваем счётчик

print(count)  # Выводим количество подходящих чисел