# Создаём список из 4 продуктов
shopping_list = ["хлеб", "молоко", "сыр", "яблоки"]

# Добавляем ещё один продукт в конец списка
shopping_list.append("шоколад")

# Выводим список
print("Список покупок:", shopping_list)

# Создаём множество с теми же продуктами
unique_items = set(shopping_list)

# Выводим множество
print("Множество продуктов:", unique_items)